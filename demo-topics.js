export function readDemo(key) {
  try { return JSON.parse(localStorage.getItem(key)) || {}; }
  catch { return {}; }
}

export function completedDemoSessions() {
  const saved=readDemo(demoLogKey);
  return Array.isArray(saved)?saved:[];
}

